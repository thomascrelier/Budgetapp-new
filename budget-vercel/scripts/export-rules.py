#!/usr/bin/env python3
"""One-off generator: exports the Python categorization rules to src/lib/rules/data.js.

Run from budget-vercel/:  python3 scripts/export-rules.py
"""
import importlib.util
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BACKEND = os.path.normpath(os.path.join(HERE, "..", "..", "backend"))
OUT = os.path.normpath(os.path.join(HERE, "..", "src", "lib", "rules", "data.js"))

# Catch-alls that filed real bills as Transfer.
CHEQUING_DROP = {"E-TRANSFER", "PREAUTHORIZED DEBIT", "Branch Transaction",
                 "Electronic Funds", "Internet Banking", "FULFILL REQUEST"}
RENTAL_ADD = [["SETTLE", "Other"], ["CLASS ACTION", "Other"], ["TO CARD", "Transfers & Payments"]]


def load(name):
    path = os.path.join(BACKEND, name + ".py")
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def main():
    cibc = load("import_cibc_nov2026")
    rental = load("import_rental_property")
    chequing = [list(r) for r in cibc.CHEQUING_RULES]
    chequing_out = [r for r in chequing if r[0] not in CHEQUING_DROP]
    card = [list(r) for r in cibc.VISA_RULES]
    rental_out = [list(r) for r in rental.CATEGORY_RULES] + RENTAL_ADD
    print("chequing: %d -> %d; card: %d; rental: %d -> %d" % (
        len(chequing), len(chequing_out), len(card), len(rental.CATEGORY_RULES), len(rental_out)))

    def block(name, rules):
        body = ",\n".join("  " + json.dumps(r, ensure_ascii=False) for r in rules)
        return "export const %s = [\n%s,\n];\n" % (name, body)

    with open(OUT, "w") as f:
        f.write("// GENERATED by scripts/export-rules.py. Do not edit by hand; re-run the script.\n\n")
        f.write(block("CHEQUING_RULES", chequing_out) + "\n")
        f.write(block("CARD_RULES", card) + "\n")
        f.write(block("RENTAL_RULES", rental_out))


if __name__ == "__main__":
    main()
